// One-shot image optimizer: converts every public/images/home/*.jpg to WebP
// and emits downscaled variants for large files so srcset has something real
// to offer. Also writes src/features/shared/assets/imageVariants.ts — the
// manifest AssetImage uses to build `srcset` at runtime.
//
//   node scripts/optimize-images.mjs
//
// Safe to re-run — overwrites its own outputs.

import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const DIR = 'public/images/home';
const MANIFEST = 'src/features/shared/assets/imageVariants.ts';
// Variant widths offered when the source is at least this wide — roughly the
// real display sizes: 480 ≈ mobile card, 960 ≈ mobile full-bleed / desktop card.
const VARIANT_TIERS = [
  { min: 1281, width: 960 },
  { min: 641, width: 480 },
];

const files = (await readdir(DIR)).filter((f) => f.endsWith('.jpg'));
const manifest = {};
let totalIn = 0;
let totalOut = 0;
const report = [];

for (const file of files) {
  const name = file.replace(/\.jpg$/, '');
  const src = path.join(DIR, file);
  const image = sharp(src);
  const meta = await image.metadata();
  const width = meta.width ?? 0;
  const { size: inSize } = await sharp(src).toBuffer().then((b) => ({ size: b.length }));

  const out = path.join(DIR, `${name}.webp`);
  await image.webp({ quality: 80 }).toFile(out);
  const variants = [];

  for (const tier of VARIANT_TIERS) {
    if (width >= tier.min) {
      const vOut = path.join(DIR, `${name}-${tier.width}.webp`);
      await sharp(src).resize({ width: tier.width }).webp({ quality: 80 }).toFile(vOut);
      variants.push(tier.width);
    }
  }

  manifest[name] = { full: width, variants };
  const { size: outSize } = await import('node:fs/promises').then((fs) => fs.stat(out));
  totalIn += inSize;
  totalOut += outSize;
  report.push(
    `${name}: ${width}px ${Math.round(inSize / 1024)}KB -> ${Math.round(outSize / 1024)}KB` +
      (variants.length ? ` (+${variants.join(',')}w)` : ''),
  );
}

const entries = Object.entries(manifest)
  .map(([k, v]) => `  '${k}': { full: ${v.full}, variants: [${v.variants.join(', ')}] },`)
  .join('\n');

await writeFile(
  MANIFEST,
  `// GENERATED by scripts/optimize-images.mjs — do not edit by hand.
// Natural width + available downscaled variants for each /images/home/*.webp.
export const IMAGE_VARIANTS: Record<string, { full: number; variants: number[] }> = {
${entries}
};
`,
);

console.log(report.join('\n'));
console.log(`\n${files.length} files: ${(totalIn / 1e6).toFixed(1)}MB -> ${(totalOut / 1e6).toFixed(1)}MB webp`);
